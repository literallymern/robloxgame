// Builds the generated reference documents (01-03 and the command reference) from the blueprint and
// the command definitions. Written to discord/docs/ by scripts/generate-docs.js; checked by test/docs.test.js.
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROLES, ROLE_BY_KEY, EVERYONE_PERMISSIONS, ROSTER_RIGHTS } from '../blueprint/roles.js';
import { CATEGORIES } from '../blueprint/channels.js';
import { compiledBlueprint, effectivePermissions, PERSONAS, BOT, BOT_PERMISSIONS, BOT_PERMISSIONS_AFTER_SETUP } from '../blueprint/compile.js';
import { TICKET_TYPES, PANELS } from '../blueprint/tickets.js';
import { PERMISSIONS, PERMISSION_DESCRIPTIONS } from '../discord/auth.js';
import { commandJson } from '../discord/commands/index.js';
import { STATE_JOBS } from '../economy/constants.js';

const here = dirname(fileURLToPath(import.meta.url));
export const docsDir = resolve(here, '..', '..', '..', 'docs');
const HEADER = '<!-- Generated by discord/bot/scripts/generate-docs.js. Do not edit by hand: change the blueprint and run `npm run generate-docs`. -->\n\n';

const roleName = (key) => (key === BOT ? 'Economy bot' : key === 'verified' ? 'Verified Member' : ROLE_BY_KEY[key]?.name ?? key);
const list = (keys) => keys.map(roleName).join(', ');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const TYPE_LABEL = { text: 'Text', announcement: 'Announcement', forum: 'Forum', voice: 'Voice' };

function whoCanView(ch) {
  if (ch.view === 'everyone') return 'Everyone (also before verification)';
  if (ch.view === 'verified') return 'All Verified Members';
  return list(ch.view);
}

function whoCanPost(ch) {
  if (ch.post === 'all') return ch.view === 'everyone' ? 'Everyone' : 'Everyone who can see it';
  if (ch.post === 'none') return ch.bot ? 'Bot and Administrators only' : 'Administrators only';
  return list(ch.post);
}


// ---------- 01 Server blueprint ----------
function serverBlueprint() {
  const out = ['# 01 · Discord Server Blueprint', '',
    'Every category and channel that `npm run setup-server` creates, in the order it creates them.',
    'Administrators can see and moderate every channel. Moderators can additionally see every channel that Verified Members can see.',
    'Channels marked "bot" give the economy bot access to post reports, panels or logs.', ''];
  let n = 0;
  for (const cat of CATEGORIES) {
    out.push(`## ${cat.name}`, '');
    if (cat.tickets) {
      out.push('Private ticket channels are created here automatically by the bot (one channel per ticket). Only the member who opened the ticket, the responsible team, Administrators and the bot can see a ticket. See "Ticket types" below.', '');
      continue;
    }
    out.push('| Channel | Type | Who can see it | Who can post | Purpose |', '|---|---|---|---|---|');
    for (const ch of cat.channels) {
      n += 1;
      const name = ch.type === 'voice' ? `🔊 ${ch.name}` : `#${ch.name}`;
      const extras = [ch.bot ? 'bot' : null, ch.manage?.length ? `moderated by ${list(ch.manage)}` : null].filter(Boolean).join('; ');
      out.push(`| ${esc(name)} | ${TYPE_LABEL[ch.type ?? 'text']}${extras ? ` (${esc(extras)})` : ''} | ${esc(whoCanView(ch))} | ${esc(ch.type === 'voice' ? (ch.post === 'all' ? 'Everyone who can see it can speak' : whoCanPost(ch)) : whoCanPost(ch))} | ${esc(ch.topic ?? '')} |`);
    }
    out.push('');
  }
  out.push(`Total: ${CATEGORIES.length} categories, ${n} channels.`, '');

  out.push('## Ticket types', '', 'Ticket buttons are posted with `npm run post-messages -- --apply` (or `/panel`).', '',
    '| Button | Panel channel | Reviewed by (besides Administrators) |', '|---|---|---|');
  for (const [, t] of Object.entries(TICKET_TYPES)) {
    const panelChannel = CATEGORIES.flatMap((c) => c.channels).find((c) => c.key === t.panel);
    out.push(`| ${t.emoji} ${esc(t.label)} | #${panelChannel?.name ?? t.panel} | ${t.reviewers.length ? esc(list(t.reviewers)) : 'Administrators only'}${t.allowRestricted ? ' (also open to Restricted Members)' : ''} |`);
  }
  out.push('', 'Rules for all tickets: at most 3 open tickets per member; closing a ticket hides it from the member; only Administrators and the bot can delete a closed ticket, and a transcript is saved to #ticket-transcripts first.', '');
  out.push('## Panels', '');
  for (const [key, p] of Object.entries(PANELS)) out.push(`- **${p.title}** (#${CATEGORIES.flatMap((c) => c.channels).find((c) => c.key === key)?.name ?? key}): ${p.description}`);
  out.push('- **Verification** (#verify): "I accept the rules" button. Gives Verified Member and New Member.',
    '- **Civilian** (#start-here): button to add or remove the Civilian role.');
  return out.join('\n');
}

// ---------- 02 Role hierarchy ----------
function roleHierarchy() {
  const out = ['# 02 · Role Hierarchy', '',
    'Roles from top to bottom, exactly as `npm run setup-server` orders them. A role can only manage roles below it, so the order matters.',
    '',
    '**Where the bot role goes:** directly below **Economic Administrator** and above **Leader of the Revolution**. The bot then can assign every government, service, civilian and community role, but never a staff role.',
    '',
    '**Rule:** fictional government authority never grants Discord permissions. Every Government, Justice, Security, Public Services and Civilian role has *no* server-wide permissions; its powers exist only inside the economy bot and in roleplay.',
    ''];
  let group = null;
  let i = 0;
  for (const r of ROLES) {
    if (r.group !== group) {
      if (group) out.push('');
      group = r.group;
      out.push(`## ${group}`, '', '| # | Role | Colour | Shown separately | Server-wide permissions | Purpose | Assigned by |', '|---|---|---|---|---|---|---|');
    }
    i += 1;
    out.push(`| ${i} | **${esc(r.name)}** | ${r.color ?? 'default'} | ${r.hoist ? 'yes' : 'no'} | ${r.permissions.length ? esc(r.permissions.join(', ')) : 'none'} | ${esc(r.purpose)} | ${esc(r.assignedBy)} |`);
    if (r.key === 'economic_administrator') {
      out.push('|  | *Ro-Nation Economy bot (managed role)* |  |  | ' + esc(BOT_PERMISSIONS_AFTER_SETUP.join(', ')) + ' | Economy, tickets, verification, rosters | Created when the bot is invited |');
    }
  }
  out.push('', '## @everyone', '', `Server-wide permissions: ${EVERYONE_PERMISSIONS.length ? EVERYONE_PERMISSIONS.join(', ') : '**none**'}. Unverified members can only read the START HERE channels (granted per channel) and press the verification button.`, '');

  out.push('## Who may assign which role with /roster', '',
    'Department leaders manage only their own department. Owner and Administrators may assign every government, justice, security and public-service role. Only the Owner can assign or remove **Leader of the Revolution**. Staff, community and automatic roles can never be assigned with /roster.', '',
    '| Role holder | May assign and remove |', '|---|---|');
  for (const [holder, roles] of Object.entries(ROSTER_RIGHTS)) out.push(`| ${esc(roleName(holder))} | ${esc(list(roles))} |`);
  out.push('', '## Automatic roles', '',
    '- **Verified Member + New Member**: verification button in #verify (accounts younger than the configured minimum age need a moderator: `/mod verify`).',
    '- **Community Member**: the bot adds it 7 days after verification and removes New Member.',
    '- **Business Owner / Business Employee**: the bot adds and removes them when businesses are approved, closed, or staff are hired or fired.',
    '- **Restricted Member**: `/mod restrict` swaps all roles of a member for this role and saves the old roles; `/mod unrestrict` restores them.', '');

  out.push('## Public-sector pay', '', 'Members holding one of these roles can work one paid shift per economic day with `/work`. Wages are paid by the treasury.', '',
    '| Role | Job title | Daily wage (KGD) | Budget line |', '|---|---|---|---|');
  for (const j of STATE_JOBS) out.push(`| ${esc(roleName(j.department))} | ${esc(j.title)} | ${(j.wage / 100).toLocaleString('en-US')} | ${j.budget} |`);
  return out.join('\n');
}

// ---------- 03 Permission matrix ----------
const SHORT = {
  unverified: 'Unv', restricted: 'Res', new_member: 'New', civilian: 'Civ', business_owner: 'Biz', police_officer: 'Pol', police_command: 'PCmd',
  intelligence: 'Int', government_official: 'Gov', secretary_economy: 'SecE', leader: 'Ldr', economic_administrator: 'EcoA', support_team: 'Sup',
  moderator: 'Mod', administrator: 'Adm', owner: 'Own', bot: 'Bot',
};

function cell(persona, ch) {
  const p = effectivePermissions(persona.roles, ch.overwrites, { type: ch.type });
  if (p.all) return 'A';
  if (!p.has('ViewChannel')) return '–';
  if (ch.type === 'voice') {
    if (!p.has('Connect')) return 'V';
    if (p.has('MoveMembers') || p.has('MuteMembers')) return 'M';
    return p.has('Speak') ? 'S' : 'L';
  }
  if (!p.has('SendMessages')) return 'R';
  return p.has('ManageMessages') ? 'M' : 'W';
}

function permissionMatrix() {
  const blueprint = compiledBlueprint();
  const out = ['# 03 · Permission Matrix', '',
    'Calculated with an offline copy of Discord\'s permission algorithm (`src/blueprint/compile.js`) from the exact overwrites the setup script writes. The automated tests in `test/permissions.test.js` check the most important rules of this table.', '',
    '## Server-wide permissions', '',
    '| Role | Server-wide permissions |', '|---|---|',
    `| @everyone | ${EVERYONE_PERMISSIONS.length ? EVERYONE_PERMISSIONS.join(', ') : 'none'} |`];
  for (const r of ROLES) out.push(`| ${esc(r.name)} | ${r.permissions.length ? esc(r.permissions.join(', ')) : 'none'} |`);
  out.push(`| Economy bot (during setup) | ${BOT_PERMISSIONS.join(', ')} + temporary Administrator (see setup guide) |`);
  out.push(`| Economy bot (normal operation) | ${BOT_PERMISSIONS_AFTER_SETUP.join(', ')} (Manage Channels only inside the TICKETS category) |`, '');

  out.push('## Channel access by member type', '', 'Columns:', '');
  for (const p of PERSONAS) out.push(`- **${SHORT[p.key]}** = ${p.label}: ${p.roles.length ? p.roles.map(roleName).join(' + ') : 'no roles'}`);
  out.push('', 'Text channels: **–** cannot see · **R** read only · **W** read and write · **M** write and moderate (delete messages, manage threads) · **A** everything (Discord Administrator).',
    'Voice channels: **–** cannot see · **L** listen only · **S** speak · **M** speak and move/mute members.', '');
  const head = `| Channel | ${PERSONAS.map((p) => SHORT[p.key]).join(' | ')} |`;
  const sep = `|---|${PERSONAS.map(() => ':-:').join('|')}|`;
  for (const cat of blueprint) {
    if (!cat.channels.length) continue;
    out.push(`### ${cat.name}`, '', head, sep);
    for (const ch of cat.channels) {
      out.push(`| ${ch.type === 'voice' ? '🔊 ' : '#'}${esc(ch.name)} | ${PERSONAS.map((p) => cell(p, ch)).join(' | ')} |`);
    }
    out.push('');
  }
  out.push('### TICKETS', '', 'Each ticket channel: the member who opened it (read, write, attach files), the reviewer roles of the ticket type, Administrators (moderate) and the bot. Nobody else. Restricted Members can only open appeal tickets.', '');

  out.push('## Economy bot permissions (in-game powers)', '',
    'These are checked by the bot, not by Discord. They come from in-game offices. Discord staff roles do not grant them (except the separate Economic Administrator staff role for technical corrections), and they never grant Discord moderation rights. The Owner can use every command as an emergency override.', '',
    '| Bot permission | What it allows | Roles |', '|---|---|---|');
  for (const [perm, roles] of Object.entries(PERMISSIONS)) out.push(`| \`${perm}\` | ${esc(PERMISSION_DESCRIPTIONS[perm] ?? '')} | ${esc(list(roles))} |`);
  out.push('', 'Additional built-in limits: officials cannot approve their own spending, registry staff cannot approve their own business, AVK officers cannot decide claims on their own policies, Economic Administrators may correct at most 10,000 KGD per action (more needs the Owner), and Central Bank financing of the treasury is Owner-only.');
  return out.join('\n');
}

// ---------- Appendix: command reference ----------
const OPTION_TYPES = { 1: 'subcommand', 2: 'group', 3: 'text', 4: 'whole number', 5: 'yes/no', 6: 'member', 7: 'channel', 8: 'role', 9: 'member or role', 10: 'number', 11: 'file' };

function commandReference() {
  const out = ['# Appendix · Slash Command Reference', '', 'Generated from the command definitions the bot registers with `npm run deploy-commands`. Replies with private data are only visible to the member who used the command.', ''];
  const optionText = (o) => `\`${o.name}\`${o.required ? '' : ' (optional)'}: ${OPTION_TYPES[o.type] ?? 'value'}${o.choices?.length ? ` (${o.choices.map((c) => c.name).join(', ')})` : ''}`;
  const sub = (prefix, s) => {
    const opts = (s.options ?? []).map(optionText);
    return `- \`/${prefix} ${s.name}\`: ${s.description}${opts.length ? `<br>Options: ${opts.join('; ')}` : ''}`;
  };
  for (const c of commandJson()) {
    out.push(`## /${c.name}`, '', c.description, '');
    const opts = c.options ?? [];
    const subs = opts.filter((o) => o.type === 1 || o.type === 2);
    if (!subs.length) {
      if (opts.length) out.push(`Options: ${opts.map(optionText).join('; ')}`, '');
      continue;
    }
    for (const s of subs) {
      if (s.type === 1) out.push(sub(c.name, s));
      else for (const ss of s.options ?? []) out.push(sub(`${c.name} ${s.name}`, ss));
    }
    out.push('');
  }
  return out.join('\n');
}

// File name → full file content.
export function generatedDocs() {
  const docs = {
    '01-server-blueprint.md': serverBlueprint(),
    '02-role-hierarchy.md': roleHierarchy(),
    '03-permission-matrix.md': permissionMatrix(),
    'appendix-command-reference.md': commandReference(),
  };
  return Object.fromEntries(Object.entries(docs).map(([name, text]) => [name, `${HEADER}${text.trim()}\n`]));
}
